    /* 词组优先表：解决「游」这类一字多义的简繁分歧
       （游泳/上游/下游 保留「游」，游戏/旅游 要用「遊」） */
    const S2T_WORDS = {
        "游戏": "遊戲", "游玩": "遊玩", "游客": "遊客", "游览": "遊覽",
        "旅游": "旅遊", "游行": "遊行", "游乐": "遊樂", "游园": "遊園",
        "游记": "遊記", "导游": "導遊", "郊游": "郊遊", "游荡": "遊蕩",
        "游牧": "遊牧", "游艇": "遊艇", "游历": "遊歷"
    };

    const SKIP_TAGS = /^(SCRIPT|STYLE|TEXTAREA|CODE|PRE|SELECT|OPTION)$/;

    let regex = null;
    function getRegex() {
        if (!regex) {
            regex = new RegExp("[" + Object.keys(S2T).join("") + "]", "g");
        }
        return regex;
    }

    function convert(text) {
        let s = String(text);
        // 只有出现「游」时才走词组表，避免每个文本节点都遍历词表
        if (s.indexOf("游") >= 0) {
            for (const k in S2T_WORDS) {
                if (s.indexOf(k) >= 0) s = s.split(k).join(S2T_WORDS[k]);
            }
        }
        const re = getRegex();
        re.lastIndex = 0;
        return s.replace(re, (ch) => S2T[ch] || ch);
    }

    function walkAttrs(el) {
        ["title", "placeholder", "aria-label", "alt"].forEach((a) => {
            const v = el.getAttribute && el.getAttribute(a);
            if (v && /[\u4e00-\u9fff]/.test(v)) el.setAttribute(a, convert(v));
        });
    }

    function walk(node) {
        if (node.nodeType === 3) {
            const t = node.nodeValue;
            if (t && /[\u4e00-\u9fff]/.test(t)) node.nodeValue = convert(t);
            return;
        }
        if (node.nodeType !== 1) return;
        const tag = node.tagName;
        if (SKIP_TAGS.test(tag)) return;
        if (node.hasAttribute("data-no-i18n")) return;
        walkAttrs(node);
        // 输入框只处理占位/标题，不进入子节点
        if (tag === "INPUT") return;
        const kids = node.childNodes;
        for (let i = 0; i < kids.length; i++) walk(kids[i]);
    }

    function convertDom(root) {
        if (!root) return;
        walk(root);
    }

    function currentLocale() {
        return localStorage.getItem("portal_locale") || "zh-CN";
    }

    /* 繁体模式：监听动态插入的节点（公告、Toast 等异步内容） */
    function observe() {
        const mo = new MutationObserver((records) => {
            for (const r of records) {
                for (const n of r.addedNodes) {
                    if (n.nodeType === 1 || n.nodeType === 3) walk(n);
                }
            }
        });
        mo.observe(document.body, { childList: true, subtree: true });
    }

    function apply(locale) {
        if (locale !== "zh-TW") return;
        // 浏览器标签页标题不在 body 内，单独转换
        if (document.title) document.title = convert(document.title);
        convertDom(document.body);
        observe();
    }

    // 暴露给设置面板
    window.I18N = { convert: convert, convertDom: convertDom, locale: currentLocale };

    // 繁体模式在 DOM 就绪后转换；脚本位于 body 末尾，直接执行即可
    if (currentLocale() === "zh-TW") {
        if (document.readyState === "loading") {
            document.addEventListener("DOMContentLoaded", () => apply("zh-TW"));
        } else {
            apply("zh-TW");
        }
    }
